create table public.quote_signatures (
  id uuid primary key default gen_random_uuid(),
  quote_id uuid not null references public.quotes(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'signed', 'countersigned', 'void')),
  language text not null default 'en' check (language in ('en', 'fr')),
  channel text not null default 'public_link' check (channel in ('public_link', 'account')),
  signer_email text not null,
  signer_user_id uuid,
  otp_hash text,
  otp_expires_at timestamptz,
  otp_attempts integer not null default 0 check (otp_attempts >= 0),
  otp_sent_count integer not null default 0 check (otp_sent_count >= 0),
  otp_last_sent_at timestamptz,
  verified_at timestamptz,
  session_token_hash text,
  signer_name text,
  signer_title text,
  signature_method text check (signature_method in ('typed', 'drawn')),
  signature_image text,
  initials text,
  initials_image text,
  acknowledgements jsonb not null default '[]'::jsonb,
  consent_text text,
  document_snapshot jsonb,
  document_hash text,
  signed_at timestamptz,
  signer_ip text,
  signer_user_agent text,
  signer_city text,
  signer_region text,
  signer_country text,
  countersigner_user_id uuid,
  countersigner_name text,
  countersigner_title text,
  countersign_method text check (countersign_method in ('typed', 'drawn')),
  countersign_image text,
  countersigner_ip text,
  countersigned_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index quote_signatures_quote_idx on public.quote_signatures (quote_id, created_at desc);
create unique index quote_signatures_one_executed on public.quote_signatures (quote_id) where status in ('signed', 'countersigned');
alter table public.quote_signatures enable row level security;
comment on table public.quote_signatures is 'E-signature ceremonies for quotes: emailed code verification, customer signature + initials, frozen document snapshot with SHA-256 hash, and owner countersignature.';
